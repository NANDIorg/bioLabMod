// Строка игроку. Отдельный модуль, потому что говорить нужно почти из
// каждого хука, а вложенную функцию одного хелпера из другого не позвать.
//
// Почему не `native_chat`. Тот кладёт строку в чат **окна** (`self.ui.chat`,
// «A line in chat from the client»), и в списке объявленных хелперов
// (`native-hooks.json`) его нет — это внутренняя мелочь клиента. Наши хуки
// серверные: правый клик по мобу, использование предмета, тик игрока на
// сервере — всё это идёт стороной сервера, и её чат до экрана игрока не
// доходит. В журнале такие строки видны как `[Server thread] [CHAT] …`, а в
// чате, который игрок читает, их нет.
//
// Правильный путь — объявленный хелпер `tell` (API: `native_tell(uuid,
// line)`): он шлёт игроку пакет системного чата, в том числе внутри хука
// действующего игрока (`lan_acting_uuid`, тогда пакет уходит сразу после
// хука). Работает и в одиночной игре (окно подключено к своему серверу как
// игрок), и в LAN, и на выделенном сервере.
//
// Если игрока нет (хук без действующего игрока, окно чужого сервера), падаем
// обратно на `native_chat`: хуже видно, но хотя бы останется в журнале.
pub fn say(game: &mut crate::game::Game<'_>, text: &str) {
    let uuid = game.native_acting_id();
    if uuid != 0 && game.native_tell(uuid, horizon_client::text::Text::literal(text)) {
        return;
    }
    game.native_chat(text);
}
