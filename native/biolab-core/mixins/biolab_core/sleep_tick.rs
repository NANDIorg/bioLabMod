// Снотворные на тике игрока (GDD 4.20, M5): моб засыпает после задержки,
// вялый бросает дальнюю цель, газовое облако дышит частицами, даёт дозу
// мобам в нём, вспыхивает у огня (эфир) и задевает игрока без противогаза.
// Всё делает `biolab_sleep::tick`; здесь — только вход.
//
// Почему тик игрока: `native_level_tick_post` в одиночной игре не
// вызывается (GDD 3.8), как и у операционной (`surgery.rs`). Часть уровня
// идёт раз за тик на уровень (`sleep_pass_due`), часть игрока — у каждого.
fn biolab_core_sleep_tick(game: &mut crate::game::Game<'_>) {
    use crate::game::biolab_core as m;
    // Сервер: у окна чужого сервера мобы — копии, их не усыпляют.
    if !game.native_on(m::ID) || game.remote.is_some() {
        return;
    }
    crate::game::biolab_sleep::tick(game);
}
