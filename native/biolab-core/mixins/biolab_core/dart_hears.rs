// Без этого флага сервер не зовёт хук попадания снарядов (`dart_hit.rs`):
// он копирует летящие снаряды каждый тик, только если кто-то слушает.
// Слушаем всегда, когда мод включён, а не только пока летит брошенный
// дротик: дротик из `/summon` или из сохранения тоже должен действовать.
// Копия — только летящих снарядов, это дёшево. Стабильный API 136.
fn biolab_core_hears_projectile_impacts(game: &crate::game::Game<'_>, hears: &mut bool) {
    use crate::game::biolab_core as m;
    if game.native_on(m::ID) {
        *hears = true;
    }
}
